## Step 2: Build Prism llama.cpp with ROCm on MI300X
```powershell
# Connect via SSH
ssh amdcloud@instance-XX.amer.datadoghq.com

# Update and install deps
sudo apt update && sudo apt install -y build-essential cmake git

# Clone prism llama.cpp fork
git clone https://github.com/prism-ml/llama.cpp.git
cd llama.cpp

# Build with ROCm backend (for MI300X)
# Note: gfx90a is MI300X architecture
cmake -B build \
  -DGGML_HIP=ON \
  -DAMDGPU_TARGETS=gfx90a \
  -DGGML_VULKAN=OFF \  # ROCm backend, not Vulkan
  -DGGML_OPENMP=ON \
  -DCMAKE_BUILD_TYPE=Release

# Build
cmake --build build --config Release -j 64

# Copy binary to working dir
cp build/bin/Release/llama-server.exe .
```

