## Expected Outcomes
| Outcome | If True | Action |
|---------|---------|--------|
| **Q4_K_M achieves 20+ tok/s on MI300X** | Ternary works on RDNA3-class | Port Q4 kernel to RX 6600 Vulkan |
| **Q3_0_ROCMFPX achieves 30+ tok/s on MI300X** | Low-bit works well | Use Q3_0 on RX 6600 (better than current 3.3) |
| **All quants < 10 tok/s on MI300X** | Instinct also limited | Focus on hybrid offload (Option 2) or quant optimization (Option 3) |
| **MI300X full ROCm fails, only CPU works** | Backend issue | Abandon GPU path, focus on CPU+GPU hybrid |

