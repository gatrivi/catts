## Step 4: Benchmark Suite
### 4.1: Baseline - CPU Only (no GPU offload)
```powershell
./llama-server.exe -m Ternary-Bonsai-2-27B-PTQ1_0.gguf \
  --device cpu \
  -ngl 0 -c 8192 \
  -ctk q8_0 -ctv q8_0 \
  -fa on --temp 0.5 --top-p 0.85 --top-k 20 \
  --port 9103
```

### 4.2: ROCm GPU Offload (full)
