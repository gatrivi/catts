## Step 6: Extract RX 6600 Porting Guide
### 6.1: Map MI300X results to RX 6600 constraints
```powershell
# RX 6600 has 8 GB VRAM, RDNA2 architecture
# MI300X has 192 GB HBM3

# Key insights to document:
1. Which quantizations fit in 8 GB VRAM on RX 6600?
   - Q4_K_M: ~8 GB (fits)
   - Q5_K_M: ~11 GB (does NOT fit, needs system RAM)
   - Q8_0: ~22 GB (does NOT fit)

2. What speedup is possible vs 3.3 tok/s baseline?
   - If MI300X Q4_0: 45 tok/s → expect 1-2 tok/s on RX 6600 (13-45x slower, but still >3.3)
   - If MI300X Q3_0: 60 tok/s → expect 2-3 tok/s on RX 6600 (2-3x improvement)

3. Is ternary Vulkan kernel feasible?
   - If MI300X shows good HIP ternary performance → port to Vulkan
   - If MI300X falls back to CPU → Vulkan kernel essential

### 6.2: Create optimized RX 6600 command
Based on benchmark results, create updated BONSAI2.cmd:

```powershell
