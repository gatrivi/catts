# AMD Developer Cloud Validation Workflow
## Bonsai 2 Ternary Vulkan Performance on MI300X
## Purpose: Benchmark Bonsai 2 on MI300X, extract configuration for RX 6600

## Prerequisites (after claiming $100 credits)
1. AMD Developer Cloud account activated
2. SSH key paired with account
3. `amdctl` or `devcloud` CLI installed
4. Access to MI300X instance (gfx90a or gfx1030)

## Step 1: Reserve MI300X Instance
```powershell
